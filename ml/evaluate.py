"""Metrics on the held-out test days, and ml/report.md."""

import math
from dataclasses import dataclass
from pathlib import Path

from sklearn.metrics import average_precision_score, brier_score_loss

from features import FEATURES
from train import TEST_FROM, VAL_FROM, Splits, Trained

CALIBRATION_BINS = 10


@dataclass
class Metrics:
    pr_auc: float
    brier: float
    precision: float
    recall: float


@dataclass
class CalibrationBin:
    low: float
    high: float
    rows: int
    mean_predicted: float
    observed_rate: float


@dataclass
class Report:
    models: dict[str, Metrics]
    calibration: list[CalibrationBin]
    threshold: float
    test_rows: int
    test_positive_rate: float
    top_coefficients: list[tuple[str, float]]


def _metrics(y: list[int], scores: list[float], flagged: list[bool]) -> Metrics:
    tp = sum(f and t == 1 for f, t in zip(flagged, y, strict=True))
    precision = tp / sum(flagged) if any(flagged) else 0.0
    return Metrics(
        pr_auc=float(average_precision_score(y, scores)),
        brier=float(brier_score_loss(y, scores)),
        precision=precision,
        recall=tp / sum(y) if any(y) else 0.0,
    )


def _calibration(y: list[int], scores: list[float]) -> list[CalibrationBin]:
    bins = []
    for i in range(CALIBRATION_BINS):
        low, high = i / CALIBRATION_BINS, (i + 1) / CALIBRATION_BINS
        last = i == CALIBRATION_BINS - 1
        pick = [j for j, s in enumerate(scores) if low <= s < high or (last and s == 1.0)]
        bins.append(
            CalibrationBin(
                low=low,
                high=high,
                rows=len(pick),
                mean_predicted=sum(scores[j] for j in pick) / len(pick) if pick else 0.0,
                observed_rate=sum(y[j] for j in pick) / len(pick) if pick else 0.0,
            )
        )
    return bins


def _rule_score(x: list[float]) -> float:
    """Simple rule: today's craving is strong, or poor sleep with high stress."""
    f = dict(zip(FEATURES, x, strict=True))
    return float(f["craving"] >= 3 or (f["poor_sleep"] == 1 and f["high_stress"] == 1))


def evaluate(trained: Trained, splits: Splits) -> Report:
    test = splits.test
    lr_scores = [float(p) for p in trained.lr.predict_proba(test.x)[:, 1]]
    gb_scores = [float(p) for p in trained.gb.predict_proba(test.x)[:, 1]]
    base = [trained.base_rate] * len(test.y)
    rule = [_rule_score(x) for x in test.x]
    cut = trained.threshold

    coefficients = trained.lr.named_steps["model"].coef_[0]
    ranked = sorted(
        zip(FEATURES, (float(c) for c in coefficients), strict=True), key=lambda p: -p[1]
    )
    return Report(
        models={
            "logistic_regression": _metrics(test.y, lr_scores, [s >= cut for s in lr_scores]),
            "gradient_boosting": _metrics(test.y, gb_scores, [s >= cut for s in gb_scores]),
            "base_rate": _metrics(test.y, base, [False] * len(base)),
            "simple_rule": _metrics(test.y, rule, [s == 1 for s in rule]),
        },
        calibration=_calibration(test.y, lr_scores),
        threshold=cut,
        test_rows=len(test.y),
        test_positive_rate=sum(test.y) / len(test.y),
        top_coefficients=ranked[:6],
    )


def quality_problems(report: Report) -> list[str]:
    """Reasons not to ship the model. CI runs `make ml`, which fails when any are found."""
    lr = report.models.get("logistic_regression")
    base = report.models.get("base_rate")
    rule = report.models.get("simple_rule")
    if lr is None or base is None or rule is None:
        return ["the report is missing the shipped model or a baseline"]
    # Every comparison with NaN is False, so NaN would otherwise slip through.
    metrics = {"PR-AUC": lr.pr_auc, "Brier": lr.brier, "recall": lr.recall}
    if not all(math.isfinite(v) for v in metrics.values()):
        return [f"{name} is not a number" for name, v in metrics.items() if not math.isfinite(v)]
    problems = []
    if lr.pr_auc <= base.pr_auc:
        problems.append(f"PR-AUC {lr.pr_auc:.3f} is no better than the base rate")
    if lr.pr_auc <= rule.pr_auc:
        problems.append(f"PR-AUC {lr.pr_auc:.3f} is no better than the simple rule")
    if lr.brier >= base.brier:
        problems.append(f"Brier {lr.brier:.3f} is no better than the base rate")
    if lr.recall == 0:
        problems.append("recall is 0: the model never flags a hard day")
    return problems


def write_report(report: Report, path: Path) -> None:
    lines = [
        "# Risk model report",
        "",
        "> **Honesty note.** This model is trained and tested on **synthetic data**",
        "> made up by `generate.py`. These numbers show the pipeline works and that it",
        "> finds the patterns planted in that data. They say **nothing** about how well",
        "> it would predict anything for real people. It is not a medical tool.",
        "",
        "Generated by `make ml`. Target: a slip that day, or a strong craving",
        "(intensity >= 3) from 17:00 on, given that day's check-in and earlier ones.",
        f"Split by day: train days 0-{VAL_FROM - 1}, validation {VAL_FROM}-{TEST_FROM - 1},"
        f" test {TEST_FROM}+. Threshold {report.threshold:.3f} (best F1 on validation).",
        f"Test rows: {report.test_rows}, of which {report.test_positive_rate:.1%} were hard days.",
        "",
        "| Model | PR-AUC | Brier | Precision | Recall |",
        "| --- | --- | --- | --- | --- |",
    ]
    names = {
        "logistic_regression": "**Logistic regression (shipped)**",
        "gradient_boosting": "Gradient boosting (comparison)",
        "base_rate": "Baseline: base rate",
        "simple_rule": "Baseline: simple rule",
    }
    for key, m in report.models.items():
        lines.append(
            f"| {names[key]} | {m.pr_auc:.3f} | {m.brier:.3f}"
            f" | {m.precision:.3f} | {m.recall:.3f} |"
        )
    lines += [
        "",
        "Precision and recall use the threshold above (base rate never flags a day;"
        " the rule flags when it fires).",
        "",
        "## Calibration (logistic regression, test days)",
        "",
        "| Predicted | Rows | Mean predicted | Observed |",
        "| --- | --- | --- | --- |",
    ]
    for b in report.calibration:
        lines.append(
            f"| {b.low:.1f}-{b.high:.1f} | {b.rows}"
            f" | {b.mean_predicted:.3f} | {b.observed_rate:.3f} |"
        )
    lines += [
        "",
        "## Strongest features (standardised coefficients)",
        "",
        *[f"- `{name}`: {coef:+.2f}" for name, coef in report.top_coefficients],
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
